import fs from 'node:fs';
import path from 'node:path';
import contents from '../util/content';

// Runs after `next build`, appending generated rules to the exported
// out/_redirects (copied from public/_redirects) so the tracked file stays
// hand-maintained. Cloudflare Pages allows 2,000 static redirects.
const exportedRedirectsPath = path.join(process.cwd(), 'out', '_redirects');

// Episode pages live at zero-padded slugs (/001). Search engines have picked
// up unpadded numbers (/1) and the RSS <guid> values (/episode/1), which 404.
function buildEpisodeRedirects(slugs: string[]): string[] {
  const lines: string[] = [];

  for (const slug of slugs) {
    if (!/^\d+$/.test(slug)) {
      continue;
    }

    const number = String(Number(slug));
    lines.push(`/episode/${number} /${slug} 301`);

    if (number !== slug) {
      lines.push(`/episode/${slug} /${slug} 301`);
      lines.push(`/${number} /${slug} 301`);
    }
  }

  return lines;
}

function generateRedirects() {
  if (!fs.existsSync(exportedRedirectsPath)) {
    throw new Error(
      `${exportedRedirectsPath} not found; run this after the static build`
    );
  }

  const slugs = contents
    .map((content) => content.frontmatter.slug)
    .filter(Boolean) as string[];
  const lines = buildEpisodeRedirects(slugs);
  const existing = fs.readFileSync(exportedRedirectsPath, 'utf-8');

  fs.writeFileSync(
    exportedRedirectsPath,
    `${existing.trimEnd()}\n\n# Generated by scripts/generate-redirects.ts\n${lines.join('\n')}\n`
  );
  console.log(`Appended ${lines.length} episode redirects to out/_redirects`);
}

if (require.main === module) {
  generateRedirects();
}

export { buildEpisodeRedirects };
