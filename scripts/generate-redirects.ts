import fs from 'node:fs';
import path from 'node:path';
import contents from '../util/content';

// Runs after `next build`, appending generated rules to the exported
// out/_redirects (copied from public/_redirects) so the tracked file stays
// hand-maintained.
//
// Cloudflare Pages allows 2,000 static redirects and 100 dynamic ones
// (splats or placeholders). Placeholders must be a whole path segment, so
// `/content/:ep.md` cannot strip `.md`. Every rule generated here is static.
const CLOUDFLARE_STATIC_REDIRECT_LIMIT = 2000;
const CLOUDFLARE_DYNAMIC_REDIRECT_LIMIT = 100;
const exportedRedirectsPath = path.join(process.cwd(), 'out', '_redirects');

// GitHub Actions checks this repo out at a fixed workspace path. That absolute
// path was serialized into the homepage and crawled as a site URL.
const CI_CONTENT_PATH_PREFIX =
  '/home/runner/work/happyhourfm/happyhourfm/content';

// Episode pages live at zero-padded slugs (/001). Search engines have picked
// up unpadded numbers (/1), the RSS <guid> values (/episode/1), and the leaked
// CI content paths, which 404.
function buildEpisodeRedirects(slugs: string[]): string[] {
  const lines: string[] = [];

  for (const slug of slugs) {
    if (!/^\d+$/.test(slug)) {
      continue;
    }

    const number = String(Number(slug));
    lines.push(`/episode/${number} /${slug} 301`);

    if (number !== slug) {
      lines.push(`/episode/${slug} /${slug} 301`);
      lines.push(`/${number} /${slug} 301`);
    }

    lines.push(`${CI_CONTENT_PATH_PREFIX}/${slug}.md /${slug} 301`);
  }

  return lines;
}

function countRedirectRules(text: string): {
  staticRules: number;
  dynamicRules: number;
} {
  let staticRules = 0;
  let dynamicRules = 0;

  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      continue;
    }

    // A rule is dynamic when its source uses a splat or a placeholder.
    // The destination may contain `:splat` for a static source.
    const source = line.split(/\s+/)[0] ?? '';
    if (/[*:]/.test(source)) {
      dynamicRules += 1;
    } else {
      staticRules += 1;
    }
  }

  return { staticRules, dynamicRules };
}

function generateRedirects() {
  if (!fs.existsSync(exportedRedirectsPath)) {
    throw new Error(
      `${exportedRedirectsPath} not found; run this after the static build`
    );
  }

  const slugs = contents
    .map((content) => content.frontmatter.slug)
    .filter(Boolean) as string[];
  const lines = buildEpisodeRedirects(slugs);
  const existing = fs.readFileSync(exportedRedirectsPath, 'utf-8');
  const next = `${existing.trimEnd()}\n\n# Generated by scripts/generate-redirects.ts\n${lines.join('\n')}\n`;
  const { staticRules, dynamicRules } = countRedirectRules(next);

  if (staticRules > CLOUDFLARE_STATIC_REDIRECT_LIMIT) {
    throw new Error(
      `out/_redirects has ${staticRules} static rules; Cloudflare Pages allows ${CLOUDFLARE_STATIC_REDIRECT_LIMIT}`
    );
  }

  if (dynamicRules > CLOUDFLARE_DYNAMIC_REDIRECT_LIMIT) {
    throw new Error(
      `out/_redirects has ${dynamicRules} dynamic rules; Cloudflare Pages allows ${CLOUDFLARE_DYNAMIC_REDIRECT_LIMIT}`
    );
  }

  fs.writeFileSync(exportedRedirectsPath, next);
  console.log(
    `Appended ${lines.length} episode redirects to out/_redirects (${staticRules} static, ${dynamicRules} dynamic)`
  );
}

if (require.main === module) {
  generateRedirects();
}

export { buildEpisodeRedirects };
